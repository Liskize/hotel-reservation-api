CREATE TABLE IF NOT EXISTS hotels (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nom VARCHAR(120) NOT NULL,
    ville VARCHAR(100) NOT NULL,
    adresse VARCHAR(255) NOT NULL,
    nombre_chambres INTEGER NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_hotels_nombre_chambres_positive CHECK (nombre_chambres > 0)
);

CREATE INDEX IF NOT EXISTS ix_hotels_ville ON hotels (ville);

CREATE TABLE IF NOT EXISTS clients (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nom VARCHAR(100) NOT NULL,
    prenom VARCHAR(100) NOT NULL,
    email VARCHAR(255) NOT NULL UNIQUE,
    telephone VARCHAR(30),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE UNIQUE INDEX IF NOT EXISTS ix_clients_email ON clients (email);

CREATE TABLE IF NOT EXISTS reservations (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    hotel_id INTEGER NOT NULL REFERENCES hotels (id) ON DELETE RESTRICT,
    client_id INTEGER NOT NULL REFERENCES clients (id) ON DELETE RESTRICT,
    date_debut DATE NOT NULL,
    date_fin DATE NOT NULL,
    statut VARCHAR(20) NOT NULL DEFAULT 'EN_ATTENTE',
    montant_total NUMERIC(10, 2),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_reservations_dates_coherentes CHECK (date_fin > date_debut),
    CONSTRAINT ck_reservations_statut_valide
        CHECK (statut IN ('EN_ATTENTE', 'CONFIRMEE', 'ANNULEE', 'TERMINEE')),
    CONSTRAINT ck_reservations_montant_positif
        CHECK (montant_total IS NULL OR montant_total >= 0),
    CONSTRAINT uq_reservations_doublon_exact
        UNIQUE (hotel_id, client_id, date_debut, date_fin)
);

CREATE INDEX IF NOT EXISTS ix_reservations_hotel_id ON reservations (hotel_id);
CREATE INDEX IF NOT EXISTS ix_reservations_client_id ON reservations (client_id);
